def tr(lang: str, key: str, /, **kwargs) -> str:
    """Translates UI key for given app language code with clean English -> Vietnamese fallback."""
    code = (lang or "vi").strip().lower()
    if code.startswith("zh"):
        code = "zh"
    else:
        code = code.split("-")[0]

    table = STRINGS.get(code) or STRINGS["en"]
    text = table.get(key)
    if text is None:
        text = STRINGS["en"].get(key)
    if text is None:
        text = STRINGS["vi"].get(key, key)
    if kwargs:
        try:
            return text.format(**kwargs)
        except Exception:
            return text
    return text

